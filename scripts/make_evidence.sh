#!/usr/bin/env bash
# Snapshot the Airflow run history and the ingestion state into evidence/airflow_runs_<date>.md.
# Run from the repo root while the Airflow stack is up (make airflow-up). Also: make evidence.
set -euo pipefail

cd "$(dirname "$0")/.."
if [[ -f .env ]]; then set -a; . ./.env; set +a; fi

COMPOSE=(docker compose -f airflow/docker-compose.yml --env-file airflow/.env)
DATE="$(date -u +%Y-%m-%d)"
OUT="evidence/airflow_runs_${DATE}.md"
mkdir -p evidence

if ! "${COMPOSE[@]}" ps --status running --services 2>/dev/null | grep -q airflow-scheduler; then
  echo "airflow-scheduler is not running; start it with: make airflow-up" >&2
  exit 1
fi

{
  echo "# Airflow evidence, ${DATE} (UTC)"
  echo
  echo "Generated by \`scripts/make_evidence.sh\` at $(date -u +%Y-%m-%dT%H:%M:%SZ)."
  echo
  for dag in conductlens_daily conductlens_weekly_full_diff conductlens_backfill; do
    echo "## DAG runs: \`${dag}\`"
    echo
    echo '```'
    "${COMPOSE[@]}" exec -T airflow-scheduler airflow dags list-runs -d "$dag" -o table 2>/dev/null || echo "(no runs)"
    echo '```'
    echo
  done
  echo "## Latest daily run, task states"
  echo
  echo '```'
  "${COMPOSE[@]}" exec -T airflow-scheduler bash -c \
    'rid=$(airflow dags list-runs -d conductlens_daily -o json 2>/dev/null | python -c "import json,sys; r=json.load(sys.stdin); print(r[0][\"run_id\"] if r else \"\")"); \
     [ -n "$rid" ] && airflow tasks states-for-dag-run conductlens_daily "$rid" -o table || echo "(no runs)"' 2>/dev/null
  echo '```'
  echo
  echo "## \`cl-ingest status\` (watermarks and last 10 load runs per sink)"
  echo
  echo '```'
  "${COMPOSE[@]}" exec -T airflow-scheduler /opt/airflow/dbt_venv/bin/cl-ingest status 2>&1 || echo "(cl-ingest status failed)"
  echo '```'
} > "$OUT"

echo "wrote $OUT"
